"""Base abstractions for classical intelligent agents in QUANTA."""

from abc import ABC, abstractmethod
from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field

from app.domain.financial_state import FinancialState
from app.domain.strategy import FinancialAction
from app.domain.financial_problem import FinancialAllocationProblem


class AgentRole(str, Enum):
    """Categorical agent roles."""
    TREASURY = "treasury"
    RISK = "risk"
    COMPLIANCE = "compliance"
    DECISION = "decision"


class ActionProposal(BaseModel):
    """Proposal generated by a specialist agent."""
    proposed_by: AgentRole
    action: FinancialAction
    confidence: float = Field(..., ge=0.0, le=1.0)
    expected_utility_delta: float = 0.0
    rationale: str = ""


class AgentAssessment(BaseModel):
    """Diagnostic opinion emitted by an agent during deliberation."""
    agent_name: str
    role: AgentRole
    is_acceptable: bool
    score: float
    findings: List[str] = Field(default_factory=list)
    suggested_actions: List[ActionProposal] = Field(default_factory=list)


class IntelligentAgent(ABC):
    """Abstract base class for deterministic intelligent agents."""

    def __init__(self, name: str, role: AgentRole):
        self.name = name
        self.role = role

    @abstractmethod
    def perceive_and_assess(
        self, state: FinancialState, problem: FinancialAllocationProblem
    ) -> AgentAssessment:
        """Perceive current state and problem context to generate an assessment."""
        pass
